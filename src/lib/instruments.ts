export let INSTRUMENTS: Instrument[] = [...DEFAULT_INSTRUMENTS];

export function setInstruments(instruments: Instrument[]) {
  INSTRUMENTS = instruments;
}

export function getInstrumentBySymbol(symbol: string): Instrument | undefined {
  if (!symbol) return INSTRUMENTS[0];
  const clean = symbol.toUpperCase().replace('-', '/');
  return (
    INSTRUMENTS.find(
      (inst) =>
        inst.symbol.toUpperCase() === clean ||
        inst.symbol.toUpperCase().replace('/', '') === clean.replace('/', '')
    ) || DEFAULT_INSTRUMENTS[0]
  );
}

export function formatPrice(price: number, digits: number = 2): string {
  if (isNaN(price)) return '0.00';
  return price.toLocaleString('en-US', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

export function formatCurrency(amount: number, currency: string = 'USD'): string {
  if (isNaN(amount)) return '$0.00';
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount);
}
